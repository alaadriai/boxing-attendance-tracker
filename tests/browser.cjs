const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const base=process.env.TRACKER_TEST_URL||'http://127.0.0.1:4173';

(async()=>{
  await fs.mkdir('test-results',{recursive:true});
  const browser=await chromium.launch({headless:true,channel:process.env.TEST_BROWSER_CHANNEL||'chrome'});
  const context=await browser.newContext({viewport:{width:1440,height:1040}});
  const page=await context.newPage();
  page.setDefaultTimeout(12000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const requests=[];page.on('request',r=>{if(/firestore|firebase/.test(r.url()))requests.push(r.url());});
  await page.clock.install({time:new Date('2026-10-19T18:15:00Z')});
  await page.goto(base+'/?demo=1');await page.waitForSelector('#headcount');
  assert.ok((await page.locator('main').innerText()).includes('Week 43 / 2026'));
  await page.locator('[data-adjust="1"]').click({clickCount:3});
  assert.equal(await page.locator('#headcount').inputValue(),'3');
  await page.reload();await page.waitForSelector('#headcount');
  assert.equal(await page.locator('#headcount').inputValue(),'3','unsaved counter survives refresh');
  await page.locator('#save-session').click();
  await page.locator('#save-session').click();
  let records=await page.evaluate(()=>JSON.parse(localStorage.getItem('arete.demo.v2.records')));
  assert.equal(records.length,1,'repeated saves update one record');
  assert.equal(records[0].date,'2026-10-19');
  await page.locator('#navigation a[href="#history"]').click();
  await page.locator('[data-backfill]').click();
  await page.locator('#backfill-form [name=date]').fill('2026-10-12');
  await page.locator('#backfill-form [name=course]').selectOption('c1');
  await page.locator('#backfill-form [type=submit]').click();
  await page.locator('#unknown-count').check();
  await page.locator('#save-session').click();
  records=await page.evaluate(()=>JSON.parse(localStorage.getItem('arete.demo.v2.records')));
  const backfilled=records.find(r=>r.date==='2026-10-12');
  assert.equal(backfilled.count,null);assert.equal(backfilled.status,'taught');assert.ok(backfilled.createdAt.startsWith('2026-10-19'));
  await page.locator('[data-today]').click();
  await page.locator('[data-course=c2]').click();
  await page.locator('[data-outcome=cancelled]').click();
  await page.locator('#reason').fill('Hall unavailable');
  await page.locator('#save-session').click();
  records=await page.evaluate(()=>JSON.parse(localStorage.getItem('arete.demo.v2.records')));
  assert.equal(records.find(r=>r.courseId==='c2').cancelled,true);
  await page.screenshot({path:'test-results/desktop-desk.png',fullPage:true});
  await page.locator('[data-view=period]').first().click();
  await page.screenshot({path:'test-results/desktop-period.png',fullPage:true});
  await page.locator('[data-view=settings]').first().click();
  await page.locator('[data-new-period]').click();
  await page.locator('#new-period-form [name=name]').fill('Variable next period');
  await page.locator('#new-period-form [name=start]').fill('2027-01-18');
  await page.locator('#new-period-form [name=end]').fill('2027-04-04');
  await page.locator('#new-period-form [type=submit]').click();
  await page.locator('#settings-form [type=submit]').click();
  const config=await page.evaluate(()=>JSON.parse(localStorage.getItem('arete.demo.v2.config')));
  assert.equal(config.periods.length,2);assert.equal(config.periods[1].end,'2027-04-04');
  assert.ok(!config.periods[1].courses[2].until,'copied dates do not retain old course cutoffs');
  await page.locator('#navigation a[href="#history"]').click();
  const recordId=backfilled.id;
  await page.locator(`[data-archive="${recordId}"]`).click();
  await page.locator('[data-confirm-archive]').click();
  records=await page.evaluate(()=>JSON.parse(localStorage.getItem('arete.demo.v2.records')));
  assert.ok(records.find(r=>r.id===recordId).deletedAt);
  await page.locator('#toast button').click();
  records=await page.evaluate(()=>JSON.parse(localStorage.getItem('arete.demo.v2.records')));
  assert.equal(records.find(r=>r.id===recordId).deletedAt,null);
  await page.evaluate(()=>{
    const records=JSON.parse(localStorage.getItem('arete.demo.v2.records'));
    records.push({...records.find(r=>r.courseId==='c1'&&r.date==='2026-10-19'),id:'legacy-duplicate'});
    localStorage.setItem('arete.demo.v2.records',JSON.stringify(records));
  });
  await page.goto(base+'/?demo=1#desk');await page.reload();await page.locator('[data-duplicates]').click();
  assert.equal(await page.locator('#modal [data-archive]').count(),2);
  await page.locator('[data-close]').click();
  await page.locator('#navigation a[href="#period"]').click();
  await page.locator('#review-period').selectOption('ws2026-1');
  assert.ok((await page.locator('main').innerText()).includes('Duplicate records'));
  assert.equal(requests.length,0,'preview makes no Firebase requests');
  await page.locator('#navigation a[href="#desk"]').click();
  await page.locator('[data-course=c1]').click();
  await page.screenshot({path:'test-results/desktop-conflicts.png',fullPage:true});
  // A fresh mobile profile exercises the uncluttered counting view.
  const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
  const phone=await mobile.newPage();phone.on('pageerror',e=>errors.push(e.message));
  await phone.clock.install({time:new Date('2026-10-20T09:00:00Z')});
  await phone.goto(base+'/?demo=1');
  await phone.locator('[data-open-missing]').click();
  assert.equal(await phone.locator('#session-date').inputValue(),'2026-10-19');
  await phone.locator('#headcount').fill('24');
  await phone.locator('#save-session').click();
  await phone.evaluate(()=>window.scrollTo(0,0));
  await phone.screenshot({path:'test-results/mobile-desk.png',fullPage:true});
  for(const hash of ['desk','history','period','insights','settings']){
    await phone.goto(base+'/?demo=1#'+hash);await phone.waitForTimeout(100);
    await phone.evaluate(()=>window.scrollTo(0,0));
    const metrics=await phone.evaluate(()=>({body:document.body.scrollWidth,width:innerWidth}));
    assert.ok(metrics.body<=metrics.width,`${hash} must not overflow mobile: ${JSON.stringify(metrics)}`);
    await phone.screenshot({path:`test-results/mobile-${hash}.png`,fullPage:true});
  }
  await phone.setViewportSize({width:320,height:740});
  await phone.goto(base+'/?demo=1#desk');
  await phone.evaluate(()=>window.scrollTo(0,0));
  assert.ok(await phone.evaluate(()=>document.body.scrollWidth<=innerWidth),'small phone overflow');
  await phone.screenshot({path:'test-results/mobile-small.png',fullPage:true});
  const assets=await phone.locator('.brand img').evaluate(img=>({loaded:img.complete&&img.naturalWidth>0,width:img.getBoundingClientRect().width}));
  assert.ok(assets.loaded&&assets.width>0,'actual brand asset renders');
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Browser checks passed: counting, durable drafts, idempotent saves, backfill, unknown counts, cancellations, variable periods, archive/undo, duplicate review, no production writes, desktop/mobile layouts.');
})().catch(error=>{console.error(error);process.exit(1);});
